"""Build a GitHub Pages artifact with deployment-prefixed routes and assets."""
import argparse
import html
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--base-path', default='/dransal')
args = parser.parse_args()
base = '/' + args.base_path.strip('/') if args.base_path.strip('/') else ''
if base and not re.fullmatch(r'(?:/[A-Za-z0-9_-]+)+', base):
    parser.error('Base path must contain only URL path segments')

subprocess.run([sys.executable, str(ROOT / 'scripts/build-homepage.py')], check=True)
output = ROOT / '_site'
if output.exists():
    if not (output / '.pages-build').is_file():
        raise SystemExit('Refusing to replace _site without its generated-build marker')
    shutil.rmtree(output)
shutil.copytree(ROOT / 'dist', output)
(output / '.pages-build').write_text('Generated by scripts/build-pages.py\n')
(output / '.nojekyll').touch()
for path in output.rglob('*.html'):
    source = path.read_text()
    source = re.sub(r'\b(href|src)=("|\')(/(?!/)[^"\']*)\2',
                    lambda match: f'{match[1]}={match[2]}{base}{match[3]}{match[2]}', source)
    source = source.replace('<html ', f'<html data-base-path="{html.escape(base, quote=True)}" ', 1)
    path.write_text(source)
print(f'Built {output.name}/ for {base or "/"}')
